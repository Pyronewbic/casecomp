const DEMO_QUERIES = Object.keys(DEMO_CARDS);

export function isDemoQuery(q) {
  return DEMO_CARDS[q.toLowerCase().trim()] != null;
}

export function getDemoResult(q) {
  const key = q.toLowerCase().trim();
  const exact = DEMO_CARDS[key];
  if (exact) return { ...exact, _demo: true };
  const partial = DEMO_QUERIES.find(k => k.includes(key) || key.includes(k));
  if (partial) return { ...DEMO_CARDS[partial], _demo: true };
  return null;
}

export function getDemoSearchResult(q, { source, condition } = {}) {
  let result = null;
  if (source) {
    const key = Object.keys(DEMO_CARDS).find(k => {
      const d = DEMO_CARDS[k];
      return d.source === source && (k.includes(q.toLowerCase().trim()) || q.toLowerCase().trim().includes(k.replace(` ${source}`, "")));
    });
    if (key) result = { ...DEMO_CARDS[key], _demo: true };
  }
  if (!result) result = getDemoResult(q);
  if (!result) {
    return {
      query: q,
      source: source || "ebay",
      listingFormat: "raw",
      activeByCountry: {},
      sold: [],
      soldSource: "demo",
      psaSignal: null,
      counts: { activeTotal: 0, sold: 0 },
      _demo: true,
      _demoNote: `No demo data for "${q}". Try: ${DEMO_QUERIES.map(k => `"${DEMO_CARDS[k].query}"`).join(", ")}`,
    };
  }
  if (condition && result.activeByCountry) {
    const filtered = {};
    for (const [country, items] of Object.entries(result.activeByCountry)) {
      filtered[country] = items.filter(i => (i.condition || "").toUpperCase().startsWith(condition.toUpperCase()));
    }
    result = { ...result, activeByCountry: filtered, counts: { ...result.counts, activeTotal: Object.values(filtered).reduce((n, arr) => n + arr.length, 0) } };
  }
  return result;
}

export function listDemoCards() {
  return DEMO_QUERIES.map(k => DEMO_CARDS[k].query);
}
